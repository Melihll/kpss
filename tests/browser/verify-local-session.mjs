// Offline evidence assertions only. This script never sends network requests.
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { assertGeometry, readEvidence } from './session-actions.cua.mjs';
const root = path.resolve(process.argv[2] ?? '.release/mobile-session-action-fix-20261008') + path.sep;
if (!root.startsWith(path.resolve('.release') + path.sep)) throw new Error('Ignored LOCAL evidence root required');
const read = async file => JSON.parse(await fs.readFile(root + file, 'utf8'));
const before = await read('local-read-models.json'), after = await read('local-final.json');
const paused = await read('local-paused1.json');
const network = await readEvidence(root, 'network.json'), ui = await readEvidence(root, 'ui-events.json');
const posts = network.filter(e => e.transport === 'live' && e.method === 'POST' && e.path.includes('/study-sessions/'));
assert.deepEqual(posts.map(e => e.path.split('/').at(-1)), ['start', 'pause', 'resume', 'pause', 'resume', 'pause', 'resume', 'finish']);
assert.equal(posts[0].status, 201);
assert.ok(posts.slice(1).every(e => e.status === 200));
const added = after.sessions.filter(s => !before.sessions.some(b => b.id === s.id));
assert.equal(added.length, 1); const session = added[0];
assert.equal(session.id, posts[0].response.id);
assert.ok(posts.slice(1).every(e => e.path.includes('/' + session.id + '/')));
assert.equal(session.status, 'completed'); assert.ok(session.accounted_at);
assert.equal(after.active.session, null);
assert.equal(paused.active.session.id, session.id); assert.equal(paused.active.paused, true);
assert.equal(paused.active.break.session_id, session.id);
assert.deepEqual(paused.progress, before.progress, 'pause does not account work');
for (const old of before.sessions) assert.deepEqual(after.sessions.find(s => s.id === old.id), old, 'old session preserved');
for (const old of before.breaks) assert.deepEqual(after.breaks.find(b => b.id === old.id), old, 'old break preserved');
assert.equal(after.tasks.length, before.tasks.length);
for (const old of before.tasks) {
  const next = after.tasks.find(t => t.id === old.id);
  if (old.id === session.task_id) assert.deepEqual({ ...next, updated_at: old.updated_at }, old, 'only task timestamp changes');
  else assert.deepEqual(next, old);
}
const breaks = after.breaks.filter(b => b.session_id === session.id);
assert.equal(breaks.length, 3); assert.ok(breaks.every(b => b.ended_at));
const breakSeconds = breaks.reduce((n, b) => n + (Date.parse(b.ended_at) - Date.parse(b.started_at)) / 1000, 0);
const elapsedSeconds = (Date.parse(session.ended_at) - Date.parse(session.started_at)) / 1000;
const expectedMinutes = Math.max(1, Math.floor(Math.max(0, elapsedSeconds - breakSeconds) / 60));
assert.equal(session.duration_minutes, expectedMinutes);
assert.equal(after.progress.length, before.progress.length);
const oldProgress = before.progress.find(p => p.task_id === session.task_id), progress = after.progress.find(p => p.task_id === session.task_id);
assert.equal(progress.actual_study_minutes - oldProgress.actual_study_minutes, expectedMinutes);
assert.equal(progress.completed_minutes - oldProgress.completed_minutes, expectedMinutes);
for (const old of before.progress.filter(p => p.task_id !== session.task_id)) assert.deepEqual(after.progress.find(p => p.task_id === old.task_id), old);
assert.equal(after.readModels.summary.todayStudyMinutes - before.readModels.summary.todayStudyMinutes, expectedMinutes);
assert.equal(after.readModels.summary.weekStudyMinutes - before.readModels.summary.weekStudyMinutes, expectedMinutes);
const remaining = after.readModels.summary.dailyPlan.tasks.find(t => t.id === session.task_id).remainingMinutes;
assert.equal(remaining, before.tasks.find(t => t.id === session.task_id).estimated_minutes - progress.completed_minutes);
for (const [phase, name] of [['live-pause1', 'Mola ver'], ['live-resume1', 'Çalışmaya devam et'], ['live-slow-pause2', 'Mola ver'], ['live-resume2-keyboard', 'Çalışmaya devam et'], ['live-pending-rerender-pause3', 'Mola ver'], ['live-resume3', 'Çalışmaya devam et'], ['live-intentional-finish', 'Çalışmayı Bitir']]) {
  const marker = await read(phase + '.json'), request = posts.find(e => e.phase === phase);
  assertGeometry(marker.before, 390);
  const clicks = ui.filter(e => e.type === 'click' && e.isTrusted && e.at >= marker.beforeAt && e.at <= request.completedAt);
  assert.equal(clicks.length, 1); assert.equal(clicks[0].target.name, name);
}
const refreshes = network.filter(e => e.transport === 'live' && ['live-refresh-running', 'live-refresh-paused'].includes(e.phase) && e.path.endsWith('/study-sessions/active') && e.method === 'GET');
assert.ok(refreshes.length >= 2);
assert.ok(refreshes.every(e => e.response.session.id === session.id));
assert.ok(refreshes.some(e => e.phase === 'live-refresh-paused' && e.response.paused));
const delayed = posts.filter(e => e.controlledDelayMs === 12000);
assert.equal(delayed.length, 2); assert.ok(delayed.every(e => e.durationMs >= 12000));
const disabled = await read('live-pending-rerender-disabled.json');
assert.ok(disabled.controls.every(c => c.disabled)); assert.equal(disabled.overlap, 0);
const burst = (await read('live-pending-rerender-result.json')).events;
assert.equal(burst.length, 30);
const pending = posts.find(e => e.phase === 'live-pending-rerender-pause3');
assert.ok(burst.every(e => e.at >= pending.at && e.at < pending.completedAt));
assert.equal((await read('live-console.json')).length, 0);
const startMarker = await read('live-start-marker.json');
assert.ok(network.filter(e => e.transport === 'live' && e.at >= startMarker.at).every(e => e.status !== null && e.status < 400));
const preflightAnomalies = network.filter(e => e.transport === 'live' && e.at < startMarker.at && (e.status === null || e.status >= 400));
const result = { result: 'PASS', sessionId: session.id, addedSessions: 1, taskCountBefore: before.tasks.length, taskCountAfter: after.tasks.length, sameSession: true, requests: posts.map(e => ({ method: e.method, path: e.path, status: e.status, outcome: e.response.outcome })), pauses: 3, resumes: 3, finishes: 1, unexpectedFinish: 0, activeSessionsAfter: 0, newBreaks: breaks.length, accounting: { rowsAdded: 0, rowsUpdated: 1, completedBefore: oldProgress.completed_minutes, completedAfter: progress.completed_minutes, expectedMinutes, elapsedSeconds, breakSeconds, remainingBefore: before.readModels.summary.dailyPlan.tasks.find(t => t.id === session.task_id).remainingMinutes, remainingAfter: remaining }, delayedPauseMs: delayed.map(e => e.durationMs), pendingRerenders: burst.length, oldSessionsPreserved: true, refreshes: refreshes.map(e => ({ phase: e.phase, sameSession: e.response.session.id === session.id, paused: e.response.paused })), measuredNetworkIssues: 0, preflightAnomalies, consoleIssues: 0 };
await fs.writeFile(root + 'session-acceptance-result.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
